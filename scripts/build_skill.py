#!/usr/bin/env python3
"""Generate the standalone global skill skills/roadmap-intake/SKILL.md from the extension's intake command.

The extension installs per project; the standalone skill works in any project and reads the library from
this repository. Generating it keeps one source of truth.

Usage: build_skill.py [--check]   (--check exits 1 when the committed skill is out of date)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "commands" / "speckit.roadmap.intake.md"
TARGET = ROOT / "skills" / "roadmap-intake" / "SKILL.md"

LOCATE = """1. **Locate the library and the roadmap.** The library root `<lib>` is `$AI_ROADMAPS_HOME` if set, else the
   directory two levels above this skill's real path (`readlink -f` of this skill's directory), else
   `~/bezerraescossia/ai-roadmaps`. It must contain `epics/`, `archetypes/` and `scripts/plan.py`;
   otherwise abort and say what is missing. In every command and path below, replace `<lib>` with that root.
   `roadmap_path` is `.specify/memory/roadmap.md` if `.specify/` exists in the current project, else
   `./roadmap.md`; `roadmap_exists` says whether that file exists.
"""


def build() -> str:
    text = SOURCE.read_text()
    description = re.search(r"^description: (.*)$", text, re.M)[1]
    body = text.split("\n---\n", 1)[1]
    body = re.sub(r"1\. Run `\{SCRIPT\}`.*?(?=\n2\. \*\*Read the constitution\*\*)", LOCATE, body, count=1, flags=re.S)
    body = body.replace(".specify/extensions/roadmap/", "<lib>/")
    header = (f"---\nname: roadmap-intake\ndescription: {description} Use at the start of a new AI project, "
              "or to amend its roadmap.\n---\n"
              "\n<!-- Generated by scripts/build_skill.py from commands/speckit.roadmap.intake.md. "
              "Do not edit by hand. -->\n")
    return header + body


if __name__ == "__main__":
    generated = build()
    if "--check" in sys.argv:
        sys.exit(0 if TARGET.is_file() and TARGET.read_text() == generated else 1)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated)
    print(f"wrote {TARGET}")
